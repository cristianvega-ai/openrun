// Shared spacing constants for context chips and related elements.
// Centralizing these values keeps spacing consistent across chips and makes
// it easy to adjust the overall rhythm in one place.

/// Vertical padding inside of a chip
pub const CHIP_VERTICAL_PADDING: f32 = 2.0;
/// Horizontal padding inside of a chip
pub const CHIP_HORIZONTAL_PADDING: f32 = 4.0;
/// Space between icon and label inside a chip
pub const CHIP_ICON_GAP: f32 = 4.0;
/// Consistent margins surrounding all chips
pub const CHIP_MARGIN: f32 = 8.0;
/// Spacing between rows when chips wrap
pub const CHIP_ROW_RUN_SPACING: f32 = 8.0;
/// Top padding factor for the Warp prompt - less top padding
pub const PROMPT_TOP_PADDING_FACTOR: f32 = 0.6;
/// Bottom padding factor for the Warp prompt - more bottom padding
pub const PROMPT_BOTTOM_PADDING_FACTOR: f32 = 1.5;
/// Bottom padding for classic prompt attach images
pub const CLASSIC_PROMPT_ATTACH_IMAGES_BOTTOM_PADDING: f32 = 10.;
